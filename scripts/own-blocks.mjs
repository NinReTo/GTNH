/**
 * Свои текстуры 16×16 для блоков, которые в игре приходят из Minecraft
 * (лава, вода, земля, листья, лампа…). Файлы игры Mojang раздавать нельзя,
 * поэтому рисунки здесь придуманы заново: узор считается по формуле, цвета
 * подобраны на глаз. С текстурами Minecraft они не совпадают ни одним пикселем
 * намеренно — совпадают только смыслом («это земля», «это лава»).
 */

const SIDE = 16;

/** Псевдослучайное число 0…1 для пикселя: одно и то же при каждом запуске. */
function noise(x, y, seed) {
  let h = (x * 374761393 + y * 668265263 + seed * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967295;
}

const pick = (shades, value) => shades[Math.min(shades.length - 1, Math.floor(value * shades.length))];

/** Рисунки: функция пикселя (x, y) → цвет #rrggbb. */
const PATTERNS = {
  // Земля: три оттенка коричневого вперемешку, редкие светлые камешки.
  dirt: (x, y) => (noise(x, y, 1) > 0.93 ? "#9a8a78" : pick(["#6b4a2f", "#7a5636", "#5c3f27"], noise(x, y, 2))),
  // Грядка: тёмная влажная земля с бороздами через каждые четыре пикселя.
  farmland: (x, y) => (y % 4 === 0 ? "#2f1d10" : pick(["#4a2f1a", "#553720", "#3f2815"], noise(x, y, 3))),
  // Доски: четыре доски поперёк, тёмный шов между ними, стык со сдвигом.
  planks: (x, y) => {
    if (y % 4 === 3) return "#6e5230";
    if (x === (Math.floor(y / 4) * 5 + 3) % SIDE) return "#7a5c36";
    return pick(["#b08a50", "#a88248", "#b8925a"], noise(x, Math.floor(y / 4), 4));
  },
  // Кирпич: ряды по четыре пикселя, кирпичи со сдвигом через ряд, светлый раствор.
  bricks: (x, y) => {
    const shift = (Math.floor(y / 4) % 2) * 4;
    if (y % 4 === 3 || (x + shift) % 8 === 7) return "#b9b2a6";
    return pick(["#96473a", "#a35040", "#8a3f33"], noise(Math.floor((x + shift) / 8), Math.floor(y / 4), 5));
  },
  // Обожжённая глина: ровная рыжая поверхность с лёгкой рябью.
  clay: (x, y) => pick(["#96593f", "#9d5f44", "#8e533a"], noise(x, y, 14)),
  // Блок пасеки (мод Forestry): жёлтые соты в шахматном порядке на тёмной рамке.
  hive: (x, y) => ((x + (Math.floor(y / 4) % 2) * 2) % 4 === 0 || y % 4 === 0 ? "#7a5a1c" : pick(["#d9a520", "#e3b53a", "#c9951a"], noise(x >> 2, y >> 2, 15))),
  // Воронка: тёмное железо с лёгкой рябью, светлая кромка по верхнему краю чаши.
  hopper: (x, y) => (y === 0 ? "#6a6a6a" : pick(["#3a3a3a", "#444444", "#333333"], noise(x, y, 16))),
  // Сундук спереди: рыжие доски, рамка на пиксель от края (сундук уже блока), шов крышки и светлая защёлка.
  chest: (x, y) => {
    if (Math.abs(x - 7.5) < 1 && y > 4 && y < 8) return "#d8d8d8";
    if (x <= 1 || y <= 2 || x >= SIDE - 2 || y === SIDE - 1 || y === 6) return "#4a3214";
    return pick(["#a8742c", "#b07c32", "#9c6a26"], noise(x, Math.floor(y / 4), 17));
  },
  // Сундук сбоку, сверху и сзади: те же доски и рамка, без защёлки.
  "chest-side": (x, y) => {
    if (x <= 1 || y <= 2 || x >= SIDE - 2 || y === SIDE - 1 || y === 6) return "#4a3214";
    return pick(["#a8742c", "#b07c32", "#9c6a26"], noise(x, Math.floor(y / 4), 18));
  },
  // Вагонетка с воронкой: без рисунка, ровный серый цвет. Им закрашивают нижнюю половину блока, в котором она стоит.
  cart: () => "#7d8791",
  // Бревно сбоку: вертикальные полосы коры разной ширины.
  log: (x, y) => (noise(x, 0, 6) > 0.72 ? "#3b2a18" : pick(["#5e4326", "#684b2b", "#553c22"], noise(x, Math.floor(y / 3), 7))),
  // Листья: пятна трёх зелёных, между ними тёмные просветы.
  leaves: (x, y) => (noise(x, y, 8) > 0.8 ? "#1c3a14" : pick(["#3f7a2a", "#4d8c33", "#356b24"], noise(x >> 1, y >> 1, 9))),
  // Лава: крупные светлые и тёмные пятна раскалённой породы.
  lava: (x, y) => pick(["#c9400a", "#e25f0e", "#f08a18", "#f7b02c"], (noise(x >> 2, y >> 2, 10) * 3 + noise(x, y, 11)) / 4),
  // Вода: синие волны — оттенок плавно меняется по диагонали, с редкими бликами.
  water: (x, y) => (noise(x, y, 12) > 0.95 ? "#7fb0f0" : pick(["#2a52be", "#3160cf", "#2548a8"], ((x + y * 2) % 8) / 8)),
  // Лампа: тёмная решётка и тёплое свечение в каждой ячейке.
  lamp: (x, y) => (x % 4 === 0 || y % 4 === 0 ? "#5a3a18" : pick(["#f0b040", "#f7c85a", "#e89a30"], noise(x >> 2, y >> 2, 13))),
};

/** Все свои блоки: имя файла (без расширения) → буфер RGB 16×16. */
export function ownBlocks() {
  return Object.entries(PATTERNS).map(([name, pattern]) => {
    const data = Buffer.alloc(SIDE * SIDE * 3);
    for (let y = 0; y < SIDE; y += 1) {
      for (let x = 0; x < SIDE; x += 1) {
        const hex = pattern(x, y);
        [1, 3, 5].forEach((at, channel) => {
          data[(y * SIDE + x) * 3 + channel] = Number.parseInt(hex.slice(at, at + 2), 16);
        });
      }
    }
    return { file: `own-${name}`, data, side: SIDE };
  });
}
