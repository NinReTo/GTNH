type BoilerTier = "bronze" | "steel";

/** Угольный котёл: дверца топки спереди, трубы на боках и сверху (MTEBoilerBronze). */
function coal(tier: BoilerTier): Faces {
  return {
    front: `boiler-coal-${tier}-front`,
    side: `boiler-${tier}-pipe-side`,
    top: `boiler-${tier}-pipe-top`,
    bottom: `hull-${tier}-bricked-bottom`,
  };
}

/** Солнечный котёл: кирпичный корпус, панель сверху, труба выхода пара на одной грани (MTEBoilerSolar). */
function solar(tier: BoilerTier): Faces {
  const hull = `hull-${tier}-bricked`;
  return { front: `boiler-${tier}-pipe-side`, side: `${hull}-side`, top: `boiler-solar-${tier}-top`, bottom: `${hull}-bottom` };
}

